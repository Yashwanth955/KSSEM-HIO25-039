  // ---------- Historical Data (Stats + Chart + Table) ----------
  static (double? value, String unit) _parseResultValue(String input) {
    final trimmed = input.trim();
    if (trimmed.isEmpty) return (null, '');
    final parts = trimmed.split(RegExp(r'\s+'));
    final numPart = parts.isNotEmpty ? parts.first : '';
    final value = double.tryParse(numPart);
    final unit = parts.length > 1 ? parts.sublist(1).join(' ') : '';
    return (value, unit);
  }

  static bool _isHigherBetterForTest(String title, String unit) {
    final t = title.toLowerCase();
    const lowerBetterTitles = [
      '30mts standing start',
      '4*10mts shuttle run',
      '800mts run',
      '1.6km run',
    ];
    if (lowerBetterTitles.any((e) => t.contains(e.toLowerCase()))) return false;
    final u = unit.toLowerCase();
    const timeUnits = [
      'sec',
      'second',
      'seconds',
      's',
      'min',
      'minute',
      'minutes',
      'ms',
    ];
    if (timeUnits.any((kw) => u.contains(kw))) return false;
    return true; // default higher is better
  }

  static pw.Widget _metricRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 2),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(label, style: pw.TextStyle(color: PdfColors.grey700)),
          pw.Text(value, style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        ],
      ),
    );
  }

  static pw.Widget _buildStatsSummary(List<TestResult> results) {
    final latest = results.last;
    final prev = results.length > 1 ? results[results.length - 2] : null;
    final (latestVal, latestUnit) = _parseResultValue(latest.resultValue);
    final (prevVal, _) = _parseResultValue(prev?.resultValue ?? '');

    final values = <double>[];
    for (final r in results) {
      final (v, _) = _parseResultValue(r.resultValue);
      if (v != null) values.add(v);
    }

    double? avg;
    double? best;
    DateTime? bestDate;
    if (values.isNotEmpty) {
      avg = values.reduce((a, b) => a + b) / values.length;
      final (_, unitProbe) = _parseResultValue(results.last.resultValue);
      final higherBetter = _isHigherBetterForTest(
        results.last.testTitle,
        unitProbe,
      );
      var bestIdx = 0;
      for (var i = 1; i < values.length; i++) {
        final better = higherBetter
            ? values[i] > values[bestIdx]
            : values[i] < values[bestIdx];
        if (better) bestIdx = i;
      }
      best = values[bestIdx];
      bestDate = results[bestIdx].date;
    }

    final change = (latestVal != null && prevVal != null)
        ? latestVal - prevVal
        : null;
    String fmt(double v) => v.toStringAsFixed(2);

    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        color: PdfColors.grey100,
        borderRadius: pw.BorderRadius.circular(6),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'Summary',
            style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 4),
          _metricRow('Attempts', results.length.toString()),
          if (avg != null)
            _metricRow(
              'Average',
              '${fmt(avg)}${latestUnit.isNotEmpty ? ' ' + latestUnit : ''}',
            ),
          if (best != null && bestDate != null)
            _metricRow(
              'Best',
              '${fmt(best)}${latestUnit.isNotEmpty ? ' ' + latestUnit : ''} (${_formatDate(bestDate)})',
            ),
          if (latestVal != null)
            _metricRow(
              'Latest',
              '${fmt(latestVal)}${latestUnit.isNotEmpty ? ' ' + latestUnit : ''} (${_formatDate(results.last.date)})',
            ),
          _metricRow(
            'Change vs previous',
            change == null
                ? 'N/A'
                : '${change >= 0 ? '+' : ''}${fmt(change)}${latestUnit.isNotEmpty ? ' ' + latestUnit : ''}',
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildHistoricalPerformance(
    String title,
    List<TestResult> results,
  ) {
    final headers = ['Date', 'Result', 'Change'];
    final rows = <List<String>>[];
    for (var i = 0; i < results.length; i++) {
      final cur = results[i];
      final (curVal, unit) = _parseResultValue(cur.resultValue);
      String changeStr;
      if (i == 0) {
        changeStr = '—';
      } else {
        final (prevVal, _) = _parseResultValue(results[i - 1].resultValue);
        if (curVal != null && prevVal != null) {
          final d = curVal - prevVal;
          changeStr =
              '${d >= 0 ? '+' : ''}${d.toStringAsFixed(2)}${unit.isNotEmpty ? ' ' + unit : ''}';
        } else {
          changeStr = 'N/A';
        }
      }
      rows.add([_formatDate(cur.date), cur.resultValue, changeStr]);
    }

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          title,
          style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
        ),
        pw.SizedBox(height: 6),
        pw.Container(
          height: 160,
          child: () {
            final points = <pw.PointChartValue>[];
            for (var i = 0; i < results.length; i++) {
              final (v, _) = _parseResultValue(results[i].resultValue);
              final y = v ?? 0.0;
              points.add(pw.PointChartValue((i + 1).toDouble(), y));
            }
            if (points.isEmpty) return pw.SizedBox();
            double minY = points
                .map((p) => p.y)
                .reduce((a, b) => a < b ? a : b);
            double maxY = points
                .map((p) => p.y)
                .reduce((a, b) => a > b ? a : b);
            if (minY == maxY) {
              minY -= 1;
              maxY += 1;
            }
            if (minY > 0) minY = 0;
            final avgY =
                points.map((p) => p.y).fold<double>(0.0, (a, b) => a + b) /
                points.length;
            final tickCount = 6;
            final span = maxY - minY;
            final step = span / (tickCount - 1);
            final yTicks = List<double>.generate(
              tickCount,
              (i) => double.parse((minY + step * i).toStringAsFixed(2)),
            );
            final monthShort = const [
              'Jan',
              'Feb',
              'Mar',
              'Apr',
              'May',
              'Jun',
              'Jul',
              'Aug',
              'Sep',
              'Oct',
              'Nov',
              'Dec',
            ];
            final xLabels = List<String>.generate(points.length, (i) {
              final d = results[i].date;
              return '${d.day} ${monthShort[d.month - 1]}';
            });
            return pw.Chart(
              grid: pw.CartesianGrid(
                xAxis: pw.FixedAxis.fromStrings(
                  xLabels,
                  marginStart: 10,
                  marginEnd: 10,
                ),
                yAxis: pw.FixedAxis(
                  yTicks,
                  format: (v) => v.toStringAsFixed(2),
                ),
              ),
              datasets: [
                pw.LineDataSet(
                  data: points,
                  drawSurface: true,
                  legend: 'Result',
                  color: PdfColors.blue,
                  surfaceOpacity: 0.15,
                  lineWidth: 2,
                  pointSize: 3,
                ),
                pw.LineDataSet(
                  data: points
                      .map((p) => pw.PointChartValue(p.x, avgY))
                      .toList(),
                  legend: 'Average',
                  color: PdfColors.red,
                  drawSurface: false,
                  lineWidth: 1,
                  pointSize: 0,
                ),
              ],
            );
          }(),
        ),
        pw.SizedBox(height: 10),
        pw.Table.fromTextArray(
          headers: headers,
          data: rows,
          headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
          headerDecoration: pw.BoxDecoration(color: PdfColors.grey300),
          cellAlignment: pw.Alignment.centerLeft,
        ),
      ],
    );
  }

  static pw.Widget _buildFooter(pw.Context context) {
    return pw.Container(
      padding: const pw.EdgeInsets.only(top: 8),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Generated by Sādhak • ${_formatDateTime(DateTime.now())}',
            style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
          ),
          pw.Text(
            'Page ${context.pageNumber}/${context.pagesCount}',
            style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
          ),
        ],
      ),
    );
  }

  static String _formatDate(DateTime d) => '${d.day}/${d.month}/${d.year}';
  static String _formatDateTime(DateTime d) =>
      '${_pad2(d.day)}/${_pad2(d.month)}/${d.year} ${_pad2(d.hour)}:${_pad2(d.minute)}';
  static String _pad2(int n) => n.toString().padLeft(2, '0');

  static Future<void> previewPdf(File file) async {
    await Printing.layoutPdf(onLayout: (_) => file.readAsBytes());
  }
}
