  /// Basic quick test report (simple version)
  static Future<File> generateTestReport({
    required String testName,
    required String score,
    required DateTime date,
    required String feedback,
    required String performanceTrend,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        margin: const pw.EdgeInsets.all(32),
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              "Athlete Performance Report",
              style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 16),
            pw.Text("Test Name: $testName"),
            pw.Text("Date: ${date.toLocal()}".split(' ')[0]),
            pw.SizedBox(height: 8),

            pw.Text("Score:", style: pw.TextStyle(fontSize: 18)),
            pw.Text(
              score,
              style: pw.TextStyle(
                fontSize: 28,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.green,
              ),
            ),
            pw.SizedBox(height: 20),

            pw.Text(
              "Performance Insight:",
              style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
            ),
            pw.Text(feedback),
            pw.SizedBox(height: 10),

            pw.Text(
              "Progress Trend:",
              style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
            ),
            pw.Text(performanceTrend),
            pw.SizedBox(height: 20),

            pw.Divider(),

            pw.Center(
              child: pw.Text(
                "Generated by Sādhak Performance App",
                style: pw.TextStyle(fontSize: 12, color: PdfColors.grey),
              ),
            ),
          ],
        ),
      ),
    );

    final dir = await getApplicationDocumentsDirectory();
    final file = File("${dir.path}/$testName-report.pdf");
    await file.writeAsBytes(await pdf.save());
    return file;
  }

  /// Full detailed report using TestReport model + historical graph & table
  static Future<void> generateAndShareReport(TestReport reportData) async {
    final pdf = pw.Document();
    final isar = IsarService();

    // Get historical results for this test
    final all = await isar.getAllTestResults();
    final results =
        all.where((r) => r.testTitle == reportData.testTitle).toList()
          ..sort((a, b) => a.date.compareTo(b.date));

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.symmetric(horizontal: 28, vertical: 24),
        footer: (context) => _buildFooter(context),
        build: (context) {
          return [
            _buildHeader(reportData.testTitle),
            pw.SizedBox(height: 16),
            _buildHeadline(reportData.headlineResult, reportData.resultSummary),
            if (results.isNotEmpty) ...[
              pw.SizedBox(height: 12),
              _buildStatsSummary(results),
            ],
            pw.SizedBox(height: 12),
            if (reportData.breakdownMetrics.isNotEmpty)
              _buildSection(
                'Performance Breakdown',
                reportData.breakdownMetrics,
              ),
            if (reportData.comparisonMetrics.isNotEmpty)
              _buildSection('Comparison', reportData.comparisonMetrics),
            if (reportData.coachTips.isNotEmpty)
              _buildCoachTips(reportData.coachTips),
            if (results.isNotEmpty) ...[
              pw.SizedBox(height: 16),
              _buildHistoricalPerformance('Historical Performance', results),
            ],
          ];
        },
      ),
    );

    await Printing.sharePdf(
      bytes: await pdf.save(),
      filename: '${reportData.testTitle.replaceAll(" ", "_")}_report.pdf',
    );
  }

